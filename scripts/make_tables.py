def build_all_tables(spec, results_root: str = "results", out_dir: Path = Path("tables")) -> List[Path]:
    out_dir = Path(out_dir)
    written: List[Path] = []

    expected: Dict[str, int] = {}
    for block in spec.blocks:
        expected[block["id"]] = int(block.get("n_seeds", spec.n_seeds))

    aggregates: Dict[str, List[Dict]] = {}
    for block in spec.blocks:
        block_id = block["id"]
        records = load_records(results_root, block_id)
        if not records:
            continue
        aggregates[block_id] = aggregate_block(
            records, n_expected_per_condition=expected.get(block_id)
        )

    reporting = spec.reporting or {}
    stats_cfg = reporting.get("statistics", {})

    builders = [
        ("E1_main_grid", table_main_grid),
        ("E1_main_grid", table_sweet_spot),
        ("E1_main_grid", table_diversity),
        ("E3_uncertainty_methods", table_uncertainty_methods),
        ("E6_operational_profiling", table_profiling),
        ("E5_long_horizon", table_forgetting),
        ("E4_sensitivity", table_sensitivity),
    ]
    for block_id, builder in builders:
        aggs = aggregates.get(block_id)
        if not aggs:
            continue
        try:
            written.extend(builder(aggs, out_dir))
        except Exception as exc:
            print(f"[tables] {builder.__name__} failed for {block_id}: {exc}")

    shift_aggs = aggregates.get("E2b_shift_real", [])
    baseline_aggs = aggregates.get("E2a_shift_baseline", [])
    if shift_aggs or baseline_aggs:
        written.extend(table_shift(shift_aggs, baseline_aggs, out_dir))

    intensity_aggs = aggregates.get("E2c_shift_intensity", [])
    if intensity_aggs:
        written.extend(table_shift(intensity_aggs, [], out_dir / "intensity"))

    # Statistics across every block that has replicated conditions.
    all_stats: List[Dict] = []
    for block_id, aggs in aggregates.items():
        try:
            all_stats.extend(
                run_statistics(
                    aggs,
                    metrics=stats_cfg.get(
                        "primary_metrics",
                        ["auc_normalized", "final_recall", "final_mAP50", "recall_variance"],
                    ),
                    reference=stats_cfg.get("reference_strategy", "bald_diversity"),
                    n_bootstrap=int(stats_cfg.get("n_bootstrap", 1000)),
                    alpha=float(stats_cfg.get("alpha", 0.05)),
                )
            )
        except Exception as exc:
            print(f"[tables] statistics failed for {block_id}: {exc}")
    if all_stats:
        written.extend(table_statistics(all_stats, out_dir))

    # A single wide CSV of every aggregate, for ad-hoc inspection.
    flat = [a for aggs in aggregates.values() for a in aggs]
    if flat:
        out_dir.mkdir(parents=True, exist_ok=True)
        df = build_dataframe(flat)
        path = out_dir / "all_aggregates.csv"
        df.to_csv(path, index=False, float_format="%.6f")
        written.append(path)

    return written


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Generate thesis tables")
    parser.add_argument("--config", default="configs/campaign.yaml")
    parser.add_argument("--results", default="results")
    parser.add_argument("--out", default="tables")
    args = parser.parse_args()

    spec = load_campaign(args.config)
    written = build_all_tables(spec, results_root=args.results, out_dir=Path(args.out))
    for path in written:
        print(f"  {path}")
    print(f"\n{len(written)} file(s) written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
