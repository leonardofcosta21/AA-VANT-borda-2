def table_diversity(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """H3/C4: direct evidence about the selection mechanism."""
    rows = []
    for agg in aggs:
        # Aggregation appends `_mean` to every run-level scalar, so the
        # per-run key `diversity_coverage_mean` becomes
        # `diversity_coverage_mean_mean` here. Checking the un-suffixed
        # name silently emptied this table.
        if agg.get("diversity_coverage_mean_mean") is None:
            continue
        rows.append(
            {
                "$L_0$": agg.get("l0_size"),
                "$B$": agg.get("budget"),
                "Strategy": pretty(agg.get("strategy")),
                "Cluster coverage $\\uparrow$": _pm(agg, "diversity_coverage_mean"),
                "Selection entropy $\\uparrow$": _pm(agg, "diversity_selection_entropy_mean"),
                "Redundancy rate $\\downarrow$": _pm(agg, "diversity_redundancy_rate_mean"),
                "AUC$_{norm}$": _pm(agg, "auc_normalized"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Diversity diagnostics of the acquisition step, measured on the "
            "selected batches themselves rather than inferred from downstream "
            "accuracy. Cluster coverage is the fraction of $k$-means clusters "
            "in the candidate pool that receive at least one annotation per "
            "cycle; redundancy rate is the fraction of selected pairs closer "
            "in embedding space than the 5th percentile of the pool's own "
            "distance distribution, which is the near-duplicate frame problem "
            "that diversity-aware selection exists to prevent."
        ),
        label="tab:diversity",
        note=(
            "These columns separate the mechanism from its effect: they show "
            "whether selection is actually more spread out, independently of "
            "whether that spreading improved mAP@50."
        ),
    )
    return _write(out_dir, "diversity", df, latex)


def table_forgetting(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """Continual-learning behaviour over a long horizon."""
    rows = []
    for agg in aggs:
        if agg.get("backward_transfer_mean") is None:
            continue
        rows.append(
            {
                "Strategy": pretty(agg.get("strategy")),
                "Cycles": agg.get("cycles"),
                "$n$": agg.get("n_seeds"),
                "BWT": _pm(agg, "backward_transfer"),
                "Forgetting $\\downarrow$": _pm(agg, "forgetting_measure"),
                "Retention (prior) $\\uparrow$": _pm(agg, "retention_mean_prior_domains"),
                "Source retention $\\uparrow$": _pm(agg, "source_retention"),
                "Stability gap $\\downarrow$": _pm(agg, "stability_gap"),
                "Plasticity $\\uparrow$": _pm(agg, "plasticity"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Catastrophic forgetting over a long adaptation horizon. Backward "
            "transfer (BWT) is the mean change on previously seen domains from "
            "first to last evaluation; the forgetting measure is the mean drop "
            "from each domain's peak, which -- unlike BWT -- cannot be masked "
            "by a domain that improved. Plasticity is the gain on the domain "
            "being adapted to, reported alongside so the stability-plasticity "
            "trade-off is visible rather than argued."
        ),
        label="tab:forgetting",
        note=(
            "Operationally, \\emph{source retention} answers the question that "
            "matters most: whether a detector adapted to a new disaster scene "
            "still finds what it was originally trained to find."
        ),
    )
    return _write(out_dir, "forgetting", df, latex)


def table_sensitivity(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """One-factor-at-a-time hyperparameter sensitivity."""
    rows = []
    for agg in sorted(
        aggs, key=lambda a: (str(a.get("sweep_param")), str(a.get("sweep_value")))
    ):
        if not agg.get("sweep_param"):
            continue
        rows.append(
            {
                "Parameter": str(agg.get("sweep_param")).replace("_", " "),
                "Value": agg.get("sweep_value"),
                "$n$": agg.get("n_seeds"),
                "AUC$_{norm}$ $\\uparrow$": _pm(agg, "auc_normalized"),
                "mAP@50": _pm(agg, "final_mAP50"),
                "Recall": _pm(agg, "final_recall"),
                "Acq. time (s/cycle)": _pm(agg, "mc_overhead_ratio", "{:.2f}"),
                "Latency (ms)": _pm(agg, "latency_ms_mean", "{:.2f}"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Hyperparameter sensitivity at $L_0 = 100$, varying one parameter "
            "at a time around the baseline configuration. The comparison of "
            "interest is not the best cell but the spread within each "
            "parameter: a parameter whose rows differ by less than the seed "
            "standard deviation is one the results do not depend on, and can "
            "be fixed by argument rather than by tuning."
        ),
        label="tab:sensitivity",
        note=(
            "One-factor-at-a-time by design: a full factorial over these four "
            "parameters is 144 cells before replication. Interaction effects "
            "are therefore out of scope and are declared as such."
        ),
    )
    return _write(out_dir, "sensitivity", df, latex)


def table_statistics(rows: List[Dict], out_dir: Path) -> List[Path]:
    """Significance tests with multiplicity correction."""
    df = pd.DataFrame(rows)
    if not df.empty:
        display = pd.DataFrame(
            {
                "Context": df["context"],
                "Metric": df["metric"].str.replace("_", " "),
                "Comparison": df["comparison"].map(
                    lambda s: " vs ".join(pretty(p.strip()) for p in s.split(" vs "))
                ),
                "$\\Delta$": df["difference"].map(lambda v: f"{v:+.4f}"),
                "95\\% CI": df.apply(
                    lambda r: f"[{r['ci_low']:.4f}, {r['ci_high']:.4f}]", axis=1
                ),
                "$p$": df["p_value"].map(lambda v: f"{v:.4f}" if pd.notnull(v) else "--"),
                "$p_{Holm}$": df["p_holm"].map(
                    lambda v: f"{v:.4f}" if pd.notnull(v) else "--"
                ),
                "Sig.": df["significant"].map(lambda b: "yes" if b else "no"),
                "$\\delta$": df["cliffs_delta"].map(lambda v: f"{v:+.2f}"),
                "Effect": df["effect"],
            }
        )
    else:
        display = df
    latex = to_latex(
        display,
        caption=(
            "Paired statistical comparisons within each experimental context. "
            "Differences are tested with the exact Wilcoxon signed-rank test on "
            "seed-paired values, corrected across comparisons with the "
            "Holm-Bonferroni procedure; confidence intervals come from 1000 "
            "bootstrap resamples of the seed pairing."
        ),
        label="tab:significance",
        note=(
            "With five seeds the smallest attainable two-sided $p$ is 0.0625, "
            "so a large Cliff's $\\delta$ accompanied by a non-significant $p$ "
            "should be read as an underpowered comparison rather than as "
            "evidence of no difference."
        ),
    )
    return _write(out_dir, "significance", df, latex)


