# LaTeX emission
# ---------------------------------------------------------------------------

def to_latex(
    df: pd.DataFrame,
    caption: str,
    label: str,
    column_format: Optional[str] = None,
    note: Optional[str] = None,
    float_format: str = "%.3f",
) -> str:
    if df.empty:
        body = "\\multicolumn{1}{c}{\\emph{no completed runs for this condition}} \\\\"
        return (
            f"% auto-generated; no data yet\n"
            f"\\begin{{table}}[ht]\n\\centering\n\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n\\begin{{tabular}}{{l}}\n\\toprule\n{body}\n"
            f"\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n"
        )

    fmt = column_format or "l" + "r" * (len(df.columns) - 1)
    latex = df.to_latex(
        index=False,
        escape=False,
        float_format=lambda v: float_format % v if pd.notnull(v) else "--",
        column_format=fmt,
        na_rep="--",
    )
    latex = latex.replace("\\toprule", "\\toprule").replace("_", "\\_")
    out = [
        "% Auto-generated by scripts/make_tables.py -- do not edit by hand.",
        "\\begin{table}[ht]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\resizebox{\\textwidth}{!}{%",
        latex.strip(),
        "}",
    ]
    if note:
        out.append(f"\\vspace{{2pt}}\n\\begin{{minipage}}{{\\textwidth}}\\footnotesize {note}\\end{{minipage}}")
    out.append("\\end{table}")
    return "\n".join(out) + "\n"


def _pm(agg: Dict, key: str, fmt: str = "{:.3f}") -> str:
    mean = agg.get(f"{key}_mean")
    std = agg.get(f"{key}_std")
    if mean is None or (isinstance(mean, float) and np.isnan(mean)):
        return "--"
    if std is None:
        return fmt.format(mean)
    return f"{fmt.format(mean)} $\\pm$ {fmt.format(std)}"


def _ci(agg: Dict, key: str, fmt: str = "{:.3f}") -> str:
    lo, hi = agg.get(f"{key}_ci_low"), agg.get(f"{key}_ci_high")
    if lo is None or hi is None:
        return "--"
    return f"[{fmt.format(lo)}, {fmt.format(hi)}]"


def _write(out_dir: Path, name: str, df: pd.DataFrame, latex: str) -> List[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / f"{name}.csv"
    tex_path = out_dir / f"{name}.tex"
    df.to_csv(csv_path, index=False, float_format="%.4f")
    tex_path.write_text(latex)
    return [csv_path, tex_path]


