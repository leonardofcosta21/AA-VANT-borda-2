def table_main_grid(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """H1/H3: strategy x L0 x budget, with both AUC forms."""
    rows = []
    for agg in sorted(
        aggs, key=lambda a: (str(a.get("dataset")), a.get("l0_size") or 0,
                             a.get("budget") or 0, str(a.get("strategy")))
    ):
        rows.append(
            {
                "Dataset": agg.get("dataset", "--"),
                "$L_0$": agg.get("l0_size"),
                "$B$": agg.get("budget"),
                "Strategy": pretty(agg.get("strategy")),
                "$n$": agg.get("n_seeds"),
                "AUC$_{norm}$ $\\uparrow$": _pm(agg, "auc_normalized"),
                "95\\% CI": _ci(agg, "auc_normalized"),
                "AUC$_{raw}$": _pm(agg, "auc", "{:.1f}"),
                "mAP@50 $\\uparrow$": _pm(agg, "final_mAP50"),
                "Recall $\\uparrow$": _pm(agg, "final_recall"),
                "Precision $\\uparrow$": _pm(agg, "final_precision"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Annotation efficiency across acquisition strategies, initial "
            "labelled set sizes $L_0$ and annotation budgets $B$ "
            "(mean $\\pm$ std over $n$ seeds). AUC$_{norm}$ is the area under "
            "the mAP@50 learning curve divided by the annotation budget, so it "
            "reads as mean detection quality per unit of annotation and is "
            "comparable across budgets; AUC$_{raw}$ is the unnormalised "
            "integral of Equation~5.1, reported for continuity with the "
            "preliminary results."
        ),
        label="tab:main_grid",
        note=(
            "Bootstrap confidence intervals use $n=1000$ resamples at "
            "$\\alpha=0.05$, resampling seeds."
        ),
    )
    return _write(out_dir, "main_grid", df, latex)


def table_sweet_spot(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """Where the proposed strategy's advantage over random is largest."""
    by_cell: Dict[tuple, Dict[str, Dict]] = {}
    for agg in aggs:
        key = (agg.get("dataset"), agg.get("l0_size"), agg.get("budget"))
        by_cell.setdefault(key, {})[str(agg.get("strategy"))] = agg

    rows = []
    for (dataset, l0, budget), strategies in sorted(
        by_cell.items(), key=lambda kv: (str(kv[0][0]), kv[0][1] or 0, kv[0][2] or 0)
    ):
        proposed = strategies.get("bald_diversity")
        baseline = strategies.get("random")
        if not proposed or not baseline:
            continue
        p_auc = proposed.get("auc_normalized_mean")
        b_auc = baseline.get("auc_normalized_mean")
        if p_auc is None or b_auc is None:
            continue
        gain = p_auc - b_auc
        rel = (gain / b_auc * 100) if b_auc else np.nan
        rows.append(
            {
                "Dataset": dataset,
                "$L_0$": l0,
                "$B$": budget,
                "Random": f"{b_auc:.3f}",
                "BALD+Div": f"{p_auc:.3f}",
                "Gain": f"{gain:+.3f}",
                "Gain (\\%)": f"{rel:+.1f}",
                "Recall gain": f"{(proposed.get('final_recall_mean') or 0) - (baseline.get('final_recall_mean') or 0):+.3f}",
            }
        )

    df = pd.DataFrame(rows)
    if not df.empty:
        df = df.sort_values("Gain", ascending=False)
    latex = to_latex(
        df,
        caption=(
            "Sweet-spot search: advantage of the proposed BALD + Diversity "
            "strategy over random sampling in normalised AUC, by initial "
            "labelled set size $L_0$ and annotation budget $B$. Rows are "
            "ordered by absolute gain, so the operating point where informed "
            "selection pays off most is the first row."
        ),
        label="tab:sweet_spot",
        note=(
            "A gain that shrinks as $L_0$ grows is the expected pattern: once "
            "the initial set already covers the class distribution, the choice "
            "of which frames to annotate next matters less."
        ),
    )
    return _write(out_dir, "sweet_spot", df, latex)


def table_shift(aggs: List[Dict], baseline_aggs: List[Dict], out_dir: Path) -> List[Path]:
    """H2: stability and recovery under covariate shift."""
    baselines = {}
    for agg in baseline_aggs:
        baselines[agg.get("pair_label")] = agg

    rows = []
    for agg in sorted(
        aggs, key=lambda a: (str(a.get("pair_label")), str(a.get("strategy")))
    ):
        pair = agg.get("pair_label")
        base = baselines.get(pair, {})
        base_recall = base.get("baseline_target_recall_mean")
        final_recall = agg.get("final_recall_mean")
        recovery = (
            f"{final_recall - base_recall:+.3f}"
            if base_recall is not None and final_recall is not None
            else "--"
        )
        rows.append(
            {
                "Shift pair": str(pair).replace("_to_", " $\\rightarrow$ "),
                "Strategy": pretty(agg.get("strategy")),
                "$n$": agg.get("n_seeds"),
                # `is not None`, not truthiness: a baseline recall of
                # exactly 0.0 is a real and important measurement (the
                # source model finding nothing at all on the target
                # domain), and must not render as missing data.
                "Recall (no adapt.)": (
                    f"{base_recall:.3f}" if base_recall is not None else "--"
                ),
                "Recall (adapted) $\\uparrow$": _pm(agg, "final_recall"),
                "Recovery": recovery,
                "mAP@50 $\\uparrow$": _pm(agg, "final_mAP50"),
                "Recall var. $\\downarrow$": _pm(agg, "recall_variance", "{:.4f}"),
                "Monotonicity $\\uparrow$": _pm(agg, "recall_monotonicity", "{:.2f}"),
                "AUC$_{norm}$ $\\uparrow$": _pm(agg, "auc_normalized"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Hypothesis H2 under real cross-dataset covariate shift. "
            "\\emph{Recall (no adapt.)} is the source-trained model evaluated "
            "on the target domain without adaptation, which is the zero point "
            "for the \\emph{Recovery} column. Recall variance is the "
            "inter-cycle variance of recall: lower means a more stable "
            "learning trajectory, which is the criterion H2 is stated in."
        ),
        label="tab:shift_h2",
        note=(
            "A Bayesian estimator satisfies H2 if it lowers recall variance "
            "relative to the deterministic estimator at comparable final "
            "recall; a variance reduction bought with a recall loss does not."
        ),
    )
    return _write(out_dir, "shift_h2", df, latex)


def table_uncertainty_methods(aggs: List[Dict], out_dir: Path) -> List[Path]:
    """Accuracy and cost of each uncertainty estimator."""
    rows = []
    for agg in sorted(aggs, key=lambda a: -(a.get("auc_normalized_mean") or 0)):
        rows.append(
            {
                "Method": pretty(agg.get("method") or agg.get("strategy")),
                "$n$": agg.get("n_seeds"),
                "AUC$_{norm}$ $\\uparrow$": _pm(agg, "auc_normalized"),
                "mAP@50 $\\uparrow$": _pm(agg, "final_mAP50"),
                "Recall $\\uparrow$": _pm(agg, "final_recall"),
                "Recall var. $\\downarrow$": _pm(agg, "recall_variance", "{:.4f}"),
                "Acq. overhead $\\times$ $\\downarrow$": _pm(agg, "mc_overhead_ratio", "{:.1f}"),
                "Deploy latency (ms)": _pm(agg, "latency_ms_mean", "{:.2f}"),
            }
        )
    df = pd.DataFrame(rows)
    latex = to_latex(
        df,
        caption=(
            "Comparison of approximate uncertainty estimators under an "
            "identical pipeline, splits and seeds. \\emph{Acq. overhead} is "
            "the cost of scoring one candidate relative to a single "
            "deterministic forward pass, and is the figure that decides "
            "whether a method is affordable during a mission; deployment "
            "latency is unaffected because uncertainty estimation runs off "
            "the real-time path."
        ),
        label="tab:uncertainty_methods",
        note=(
            "Deep Ensembles additionally require $M$ sets of weights in "
            "storage and $M$ full training runs, a cost not visible in the "
            "per-candidate overhead column."
        ),
    )
    return _write(out_dir, "uncertainty_methods", df, latex)


