PRETTY = {
    "random": "Random",
    "deterministic": "Deterministic",
    "bald_only": "BALD-only",
    "bald_diversity": "BALD + Diversity",
    "mc_dropout": "MC Dropout",
    "deep_ensemble": "Deep Ensemble (5)",
    "conformal": "Conformal",
    "swag": "SWAG",
    "bsb": "BSB",
    "psb": "PSB",
    "bsb_diversity": "BSB + Diversity",
}


def pretty(name) -> str:
    return PRETTY.get(str(name), str(name))


