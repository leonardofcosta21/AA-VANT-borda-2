#!/usr/bin/env python3
"""
Build every table the thesis needs, as CSV and as LaTeX.

The tables are generated from the stored run records, never typed by
hand, so a number in the document is always the number the code produced.
Each emitted .tex carries a comment naming the block and the commit it
came from, which is how a table in Chapter 6 stays traceable to the run
that made it.

Two conventions run through all of it.

Both AUC forms, always. The raw integral is kept for continuity with the
preliminary results (the 240.65 in the current abstract), and the
normalised value is printed beside it because the board asked for a
number a reader can interpret without knowing the budget.

Uncertainty is never dropped. Every mean carries its standard deviation
across seeds, and the primary tables carry the bootstrap interval too. A
bare mean over five seeds is not a result.
"""

